// Tiny i18n helper for the partner and field (technician) screens.
// No library: a flat key → string dictionary per language, English fallback.
import { createElement, useEffect, useState } from 'react';

export const LANGS = [['en', 'English'], ['gu', 'ગુજરાતી'], ['hi', 'हिंदी']];
export const LANG_KEY = 'solarcrm.lang';
const EVENT = 'solarcrm:lang';
const CODES = LANGS.map(([c]) => c);

export function getLang() {
  try {
    const v = globalThis.localStorage?.getItem(LANG_KEY);
    return CODES.includes(v) ? v : 'en';
  } catch {
    return 'en';
  }
}

export function setLang(lang) {
  const v = CODES.includes(lang) ? lang : 'en';
  try { globalThis.localStorage?.setItem(LANG_KEY, v); } catch { /* storage blocked: language still changes for this render */ }
  memo = v;
  try { globalThis.window?.dispatchEvent(new CustomEvent(EVENT, { detail: v })); } catch { /* no window (tests) */ }
}

// Last chosen language, so the switch works even when storage is blocked.
let memo = null;
const current = () => memo || getLang();

/** Re-renders the calling component whenever the language changes (here or in another tab). */
export function useLang() {
  const [lang, set] = useState(current);
  useEffect(() => {
    const on = () => set(current());
    const onStorage = (e) => { if (e.key === LANG_KEY) { memo = null; on(); } };
    window.addEventListener(EVENT, on);
    window.addEventListener('storage', onStorage);
    return () => { window.removeEventListener(EVENT, on); window.removeEventListener('storage', onStorage); };
  }, []);
  return lang;
}

/** Translate `key`, replacing `{name}` placeholders from `vars`. Missing keys fall back to English, then to the key. */
export function t(key, vars, lang = current()) {
  const s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
}

/** Compact English / ગુજરાતી / हिंदी switch. */
export function LangSwitch() {
  const lang = useLang();
  return createElement('div', { className: 'lang-switch', role: 'group', 'aria-label': 'Language / ભાષા / भाषा' },
    LANGS.map(([code, label]) => createElement('button', {
      key: code, type: 'button', lang: code, className: lang === code ? 'on' : '', 'aria-pressed': lang === code, onClick: () => setLang(code),
    }, label)));
}

