import assert from 'node:assert/strict';
import {namesMatch,cleanNameVerification} from './nameVerification.js';
assert.equal(namesMatch('Ramesh Patel','RAMESH PATEL'),true);
assert.equal(namesMatch('',''),false);
assert.throws(()=>cleanNameVerification({discomName:'A',bankName:'A'}),/Confirm/);
assert.equal(cleanNameVerification({discomName:'A',bankName:'A',bankConfirmed:true,reviewStatus:'matches'}).match,true);
assert.equal(cleanNameVerification({discomName:'A',bankName:'B',bankConfirmed:true,reviewStatus:'change_needed'}).resolution,null);
assert.equal(cleanNameVerification({discomName:'A',bankName:'B',bankConfirmed:true,reviewStatus:'matches'}).resolution,'Accepted as same person');
assert.throws(()=>cleanNameVerification({discomName:'A',bankName:'A',bankConfirmed:true,billUrl:'javascript:alert(1)'}),/link/);
assert.equal(cleanNameVerification({discomName:'A',bankName:'A',bankConfirmed:true,bankUrl:'https://drive.google.com/file/d/demo'}).bankUrl,'https://drive.google.com/file/d/demo');
console.log('Manual name verification and document link checks passed');
