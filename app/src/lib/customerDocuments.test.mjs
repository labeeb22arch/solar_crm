import assert from 'node:assert/strict';
import { CUSTOMER_DOCUMENTS,findDocument,changeCustomerDocument,cleanDocumentUrl,changeCustomerResource } from './customerDocuments.js';
assert.equal(new Set(CUSTOMER_DOCUMENTS.map(d=>d.key)).size,CUSTOMER_DOCUMENTS.length);
const doc=key=>CUSTOMER_DOCUMENTS.find(d=>d.key===key);
const project={drive:[{slot:'Electricity bill',present:true,url:'https://drive.google.com/file/d/old',by:'A',at:'2026-10-01'}, {slot:'Legacy document',present:true}]};
const drive=changeCustomerDocument(project,'light_bill',{url:'https://drive.google.com/file/d/new'},'B','2026-10-22');
assert.equal(drive.length,2,'Reuse the existing slot rather than duplicate it');
assert.equal(drive[0].slot,'Electricity bill','Keep legacy slot names for existing consumers');
assert.equal(drive[0].present,true);
assert.equal(drive[0].versions[0].url,'https://drive.google.com/file/d/old');
assert.equal(project.drive[0].url,'https://drive.google.com/file/d/old','Do not mutate input');
assert.throws(()=>changeCustomerDocument({drive},'light_bill',{checked:false},'B','now'),/already marked/);
assert.equal(changeCustomerDocument({},'pan',{checked:true},'A','now')[0].present,true);
assert.equal(findDocument({docLinks:{proposal:{url:'https://drive.google.com/file/d/quote'}}},doc('quotation')).url,'https://drive.google.com/file/d/quote');
assert.equal(findDocument({drive:[{slot:'Site survey photos',present:true}]},doc('site_feasibility')).present,false,'Do not confuse a report with photos');
assert.equal(cleanDocumentUrl('https://drive.google.com/drive/folders/folder','folder'),'https://drive.google.com/drive/folders/folder');
assert.equal(cleanDocumentUrl('https://maps.app.goo.gl/demo','location'),'https://maps.app.goo.gl/demo');
for(const value of ['javascript:alert(1)','https://drive.google.com.evil.com/file','https://user:password@drive.google.com/file','http://drive.google.com/file'])assert.throws(()=>cleanDocumentUrl(value));
assert.throws(()=>cleanDocumentUrl('https://drive.google.com/file/d/file','folder'));
assert.throws(()=>cleanDocumentUrl('https://example.com','location'));
const folder=changeCustomerResource({url:'https://drive.google.com/drive/folders/old',by:'A',at:'before'},'https://drive.google.com/drive/folders/new','folder','B','now');
assert.equal(folder.versions[0].by,'A');
assert.equal(folder.by,'B');
console.log('Document catalogue, legacy slots, file versions and folder/location links passed');
