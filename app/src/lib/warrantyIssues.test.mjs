import assert from 'node:assert/strict';
import { recordWarrantyIssue } from './warrantyIssues.js';
const context = { at: '2026-10-21T10:00:00Z', today: '2026-10-21', by: 'Admin', newId: 'issue-1' };
const input = { title: 'Inverter fault', description: 'Error E01', equipment: 'Inverter', serial: 'INV001', raisedDate: '2026-10-01', status: 'open', assignedTo: 'Crew Alpha' };
const raised = recordWarrantyIssue([], null, input, context);
assert.equal(raised[0].raisedDate, '2026-10-01');
assert.equal(raised[0].history.length, 1);
const solved = recordWarrantyIssue(raised, 'issue-1', { status: 'resolved', assignedTo: 'Crew Alpha', resolvedDate: '2026-10-03', resolution: 'Replaced connector', note: 'Tested on site' }, { ...context, newId: 'event-2' });
assert.equal(solved[0].resolvedDate, '2026-10-03');
assert.equal(solved[0].history.length, 2);
assert.equal(raised[0].status, 'open', 'prior input not mutated');
const reopened = recordWarrantyIssue(solved, 'issue-1', { status: 'in_progress', assignedTo: 'Crew Beta', note: 'Fault returned' }, { ...context, newId: 'event-3' });
assert.equal(reopened[0].resolvedDate, '');
assert.equal(reopened[0].history[1].resolution, 'Replaced connector', 'previous resolution retained after reopening');
assert.equal(reopened[0].history[2].previousStatus, 'resolved');
assert.equal(reopened[0].history[0].assignedTo, 'Crew Alpha');
assert.throws(() => recordWarrantyIssue(raised, 'issue-1', { status: 'resolved', resolvedDate: '2026-09-30', resolution: 'Done' }, context), /between/);
assert.throws(() => recordWarrantyIssue(raised, 'issue-1', { status: 'resolved', resolvedDate: '2026-10-03', resolution: '' }, context), /how/);
assert.throws(() => recordWarrantyIssue([], null, { ...input, raisedDate: '2026-10-22' }, context), /date raised/);
assert.throws(() => recordWarrantyIssue([], null, { ...input, raisedDate: '2026-02-30' }, context), /date raised/);
assert.throws(() => recordWarrantyIssue(raised, 'missing', input, context), /not found/);
assert.throws(() => recordWarrantyIssue(raised, 'issue-1', { status: 'open', assignedTo: 'Crew Alpha' }, context), /Add a note/);
assert.equal(recordWarrantyIssue(raised, 'issue-1', { status: 'open', assignedTo: 'Crew Alpha', note: 'Customer contacted' }, { ...context, newId: 'note-1' })[0].history.length, 2);
console.log('Warranty issue history lifecycle checks passed');
