import assert from 'node:assert/strict';
import { makeBOMVersion, changeBOMVersion, pendingBOMUpload } from './procurement.js';
import { makeBOMPdf } from './bomPdf.js';
const inventory=[{sku:'P1',name:'Solar panel',unit:'pcs'}];
const version=makeBOMVersion([],{lines:[{sku:'P1',qty:'4'}],notes:'Roof A'},inventory,'Staff A','2026-10-21T10:00:00Z','v1');
assert.equal(version.version,1);
assert.equal(version.lines[0].qty,4);
const downloaded=changeBOMVersion([version],'v1','downloaded',{},'Staff B','2026-10-21T11:00:00Z');
assert.equal(pendingBOMUpload(downloaded[0]).by,'Staff B');
assert.equal(version.events.length,0);
const uploaded=changeBOMVersion(downloaded,'v1','uploaded',{url:'https://drive.google.com/file/test'},'Staff C','2026-10-21T12:00:00Z');
assert.equal(pendingBOMUpload(uploaded[0]),null);
assert.equal(uploaded[0].upload.by,'Staff C');
const next=makeBOMVersion(uploaded,{lines:[{sku:'P1',qty:5}]},inventory,'Staff A','2026-10-21T13:00:00Z','v2');
assert.equal(next.version,2);
assert.equal(next.upload,null);
assert.equal(uploaded[0].lines[0].qty,4,'old version stays intact');
assert.throws(()=>changeBOMVersion(uploaded,'v2','uploaded',{url:'https://example.com'},'Staff','now'),/not found/);
assert.throws(()=>changeBOMVersion(uploaded,'v1','uploaded',{url:'javascript:alert(1)'},'Staff','now'),/http/);
assert.throws(()=>makeBOMVersion([],{lines:[{sku:'P1',qty:-1}]},inventory,'Staff','now','v1'),/quantities/);
assert.throws(()=>makeBOMVersion([],{lines:[{sku:'P1',qty:1.5}]},inventory,'Staff','now','v1'),/quantities/);
assert.throws(()=>makeBOMVersion([],{lines:[{sku:'P1',qty:1},{sku:'P1',qty:2}]},inventory,'Staff','now','v1'),/quantities/);
const pdf=await makeBOMPdf({name:'Test customer',crn:'CRN-TEST',city:'Deesa',kwp:3},{...version,lines:Array.from({length:55},(_,i)=>({...version.lines[0],name:`Panel material ${i+1}`}))});
assert.ok(pdf.getNumberOfPages()>1);
const output=pdf.output();
assert.ok(output.includes('MATERIAL PROCUREMENT'));
assert.ok(output.includes('Panel material 55'));
assert.ok(output.includes('Store checked by'));
console.log('BOM version, upload trail and multipage PDF checks passed');
