import assert from 'node:assert/strict';
import { warrantyEnd, warrantyRecord, cleanWarranty } from './warranty.js';
assert.equal(warrantyEnd('2026-10-21', 5), '2031-10-21');
assert.equal(warrantyEnd('2024-02-29', 5), '2029-02-28');
assert.equal(warrantyEnd('', 5), null);
assert.equal(warrantyEnd('2026-10-21', ''), null, 'unknown equipment terms do not get invented dates');
const project = { id: 'P1', tracks: { supply: [{ key: 'installation', status: 'done', updatedAt: '2026-10-18T10:00:00Z' }], grid: [], closure: [{ key: 'invoice', status: 'not_started', updatedAt: '2026-10-19T10:00:00Z' }] }, serials: { modules: ['PANEL001', 'PANEL002'], inverter: 'INV001' } };
const initial = warrantyRecord(project);
assert.equal(initial.invoiceDate, '', 'an unissued invoice has no date');
assert.equal(initial.startDate, '2026-10-18', 'installation date used before invoice recorded');
assert.equal(initial.terms[0].until, '2031-10-18');
assert.equal(initial.inverterYears, '');
assert.equal(initial.moduleMake, '');
assert.deepEqual(initial.moduleSerials, ['PANEL001', 'PANEL002']);
assert.equal(initial.inverterSerial, 'INV001');
const saved = warrantyRecord({ ...project, warranty: { invoiceDate: '2026-10-20', inverterYears: 7, moduleProductYears: 12 } });
assert.equal(saved.startDate, '2026-10-20');
assert.equal(saved.terms.find((t) => t.key === 'inverterYears').until, '2033-10-20');
assert.equal(warrantyRecord({ ...project, warranty: { invoiceDate: '2026-10-20', startDate: '2026-10-22' } }).startDate, '2026-10-22');
assert.throws(() => cleanWarranty({ certificateUrl: 'javascript:alert(1)' }), /http/);
assert.throws(() => cleanWarranty({ invoiceDate: '2026-02-30' }), /dates/);
assert.throws(() => cleanWarranty({ inverterYears: '-5' }), /valid/);
assert.throws(() => cleanWarranty({ workmanshipYears: '5.5' }), /valid/);
assert.equal(cleanWarranty({ moduleMake: ' Brand ', moduleWp: '540' }).moduleMake, 'Brand');
assert.equal(cleanWarranty({ moduleWp: '540' }).moduleWp, 540);
assert.equal('pid' in cleanWarranty({ pid: 'other' }), false);
console.log('Warranty date, serial and validation checks passed');
