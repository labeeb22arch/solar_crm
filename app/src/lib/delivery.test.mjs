import assert from 'node:assert/strict';
import { changeDelivery, combineBOM } from './delivery.js';
const initial = { inventory: [{ sku: 'panel', name: 'Panels', stock: 20, reserved: 3 }], batches: [] };
const payload = { id: 'batch-1', vehicle: 'GJ01', team: 'T1', date: '2026-10-21', customers: [{ id: 'customer-1' }], lines: [{ sku: 'panel', name: 'Panels', qty: 5, unit: 'pcs' }] };
const planned = changeDelivery(initial, 'create', payload, 'now');
assert.deepEqual(planned.inventory[0], { sku: 'panel', name: 'Panels', stock: 20, reserved: 8 });
assert.equal(initial.inventory[0].reserved, 3, 'does not mutate input');
assert.throws(() => changeDelivery(planned, 'loaded', { id: 'batch-1', checked: [] }, 'now'), /Check every/);
const loaded = changeDelivery(planned, 'loaded', { id: 'batch-1', checked: ['panel'] }, 'later');
assert.equal(loaded.inventory[0].stock, 15);
assert.equal(loaded.inventory[0].reserved, 3);
assert.deepEqual(changeDelivery(loaded, 'loaded', { id: 'batch-1' }, 'again'), loaded, 'repeated load is idempotent');
const delivered = changeDelivery(loaded, 'delivered', { id: 'batch-1' }, 'later');
assert.equal(delivered.inventory[0].stock, 15, 'delivery does not deduct twice');
assert.deepEqual(changeDelivery(delivered, 'loaded', { id: 'batch-1' }, 'again'), delivered);
const cancelled = changeDelivery(planned, 'cancelled', { id: 'batch-1' }, 'later');
assert.equal(cancelled.inventory[0].stock, 20);
assert.equal(cancelled.inventory[0].reserved, 3);
assert.throws(() => changeDelivery(loaded, 'cancelled', { id: 'batch-1' }, 'now'), /cannot move/);
assert.throws(() => changeDelivery(planned, 'create', { ...payload, id: 'batch-2' }, 'now'), /already has/);
assert.throws(() => changeDelivery(initial, 'create', { ...payload, lines: [{ sku: 'panel', qty: 99 }] }, 'now'), /Not enough/);
assert.throws(() => changeDelivery(initial, 'create', { ...payload, lines: [{ sku: 'panel', qty: -1 }] }, 'now'), /Invalid/);
assert.deepEqual(combineBOM([{ lines: payload.lines }, { lines: payload.lines }]), [{ sku: 'panel', name: 'Panels', qty: 10, unit: 'pcs' }]);
const multi = { ...payload, lines: [...payload.lines, { sku: 'missing', qty: 1 }] };
assert.throws(() => changeDelivery(initial, 'create', multi, 'now'));
assert.equal(initial.inventory[0].reserved, 3, 'failed multi-line reservation leaves all stock unchanged');
console.log('Delivery stock lifecycle checks passed');
