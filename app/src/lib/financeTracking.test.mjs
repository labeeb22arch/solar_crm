import assert from 'node:assert/strict';
import { appendTracking, eligibleTracking, trackingStatus } from './financeTracking.js';
const context={at:'2026-10-21T10:00:00Z',today:'2026-10-21',id:'1',by:'Staff',previousStatus:'not_applied'};
assert.equal(eligibleTracking({paymentMethod:'Cash'},'loan'),false);
assert.equal(eligibleTracking({paymentMethod:'Bank Solar Loan'},'loan'),true);
assert.equal(eligibleTracking({scheme:'pm_surya_ghar'},'subsidy'),true);
assert.equal(eligibleTracking({type:'Residential'},'subsidy'),false);
assert.equal(eligibleTracking({subsidy:[{status:'Applied'}]},'subsidy'),true);
assert.equal(trackingStatus({subsidy:[{status:'Credited to customer account'}]},'subsidy'),'received');
assert.equal(trackingStatus({tracks:{finance:[{key:'sanction',status:'done'}]}},'loan'),'approved');
const applied=appendTracking({},'subsidy',{status:'applied',date:'2026-10-01',note:'Filed'},context);
const rejected=appendTracking(applied,'subsidy',{status:'rejected',date:'2026-10-03',note:'Name mismatch'},{...context,id:'2',previousStatus:'applied'});
const retry=appendTracking(rejected,'subsidy',{status:'reapply',date:'2026-10-05',note:'Corrected papers'},{...context,id:'3',previousStatus:'rejected'});
const received=appendTracking(retry,'subsidy',{status:'received',date:'2026-10-20',amount:'78000'},{...context,id:'4',previousStatus:'reapply'});
assert.equal(received.history.length,4);
assert.equal(received.history[1].note,'Name mismatch');
assert.equal(received.history[3].amount,78000);
assert.equal(applied.history.length,1);
assert.throws(()=>appendTracking({},'subsidy',{status:'rejected',date:'2026-10-20'},context),/reason/);
assert.throws(()=>appendTracking({},'loan',{status:'reapply',date:'2026-10-20'},context),/rejection/);
assert.throws(()=>appendTracking({},'subsidy',{status:'applied',date:'2026-02-30'},context),/valid date/);
assert.throws(()=>appendTracking({},'subsidy',{status:'received',date:'2026-10-22'},context),/valid date/);
assert.throws(()=>appendTracking({},'loan',{status:'approved',date:'2026-10-20',amount:-1},context),/amount/);
console.log('Loan and subsidy status/history checks passed');
