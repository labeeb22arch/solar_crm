import assert from 'node:assert/strict';
import { operationsOptions,changeOperationsOption,keepCurrentOption,OPERATIONS_CATEGORIES } from './operationsLists.js';
const defaults=operationsOptions({},'panel_brands');
assert.ok(defaults.some((option)=>option.name==='ADANI'));
const legacy=operationsOptions({brands:[{id:'saved',name:'Existing Sunpay brand',type:'panel'}]},'panel_brands');
assert.ok(legacy.some((option)=>option.name==='Existing Sunpay brand'));
const original={registrations:[{name:'EPC registration'}]};
const added=changeOperationsOption(original,'panel_brands','add',{name:'Test Panels'},'Admin','2026-10-21','new');
assert.equal(original.optionLists,undefined,'does not mutate existing settings');
assert.deepEqual(added.registrations,original.registrations);
assert.equal(operationsOptions(added,'panel_brands').at(-1).value,'Test Panels');
const renamed=changeOperationsOption(added,'panel_brands','rename',{id:'new',name:'Renamed Panels'},'Admin','2026-10-21','evt1');
const renamedOption=operationsOptions(renamed,'panel_brands').find((o)=>o.id==='new');
assert.equal(renamedOption.name,'Renamed Panels');
assert.equal(renamedOption.value,'Test Panels','renaming never changes the stored customer value');
const archived=changeOperationsOption(renamed,'panel_brands','archive',{id:'new'},'Admin','2026-10-21','evt2');
assert.ok(!operationsOptions(archived,'panel_brands').some((o)=>o.id==='new'));
assert.ok(operationsOptions(archived,'panel_brands',true).some((o)=>o.id==='new'));
assert.ok(keepCurrentOption(operationsOptions(archived,'panel_brands'),'Test Panels').some((o)=>o.value==='Test Panels'));
const restored=changeOperationsOption(archived,'panel_brands','restore',{id:'new'},'Admin','2026-10-21','evt3');
assert.ok(operationsOptions(restored,'panel_brands').some((o)=>o.id==='new'));
assert.throws(()=>changeOperationsOption(restored,'panel_brands','add',{name:' adani '},'Admin','now','duplicate'),/already exists/);
assert.throws(()=>changeOperationsOption(restored,'bad','add',{name:'X'},'Admin','now','x'),/category/);
assert.equal(restored.history.length,4);
assert.deepEqual(operationsOptions({optionLists:{panel_brands:[]}},'panel_brands'),[],'empty managed list stays empty');
assert.equal(operationsOptions({},'schemes').find((o)=>o.name==='PM Surya Ghar').value,'pm_surya_ghar');
assert.ok(OPERATIONS_CATEGORIES.length>=16);
console.log('Operations lists, migration, rename, archive and restore checks passed');
